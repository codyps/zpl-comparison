"""Generate browsable printer/render/difference pages and verify their evidence."""

import argparse
import json
import os
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent
sys.path.insert(0, str(ROOT))
from accuracy.run import LIBRARIES, compare, gray, sha
from report import NAMES, table


def validate(data, dest):
    cases = {c["id"]: c for c in data["cases"]}
    expected = {(cid, lib) for cid in cases for lib in LIBRARIES}
    rows = {(r["case"], r["library"]): r for r in data["results"]}
    if (
        not cases
        or len(cases) != len(data["cases"])
        or len(rows) != len(data["results"])
        or set(rows) != expected
    ):
        raise ValueError("Expected exactly one result per case and renderer")
    for cid, case in cases.items():
        for field, digest in (("zpl", "zpl_sha256"), ("reference", "png_sha256")):
            if sha(REPO / case[field]) != case[digest]:
                raise ValueError(f"Changed {field}: {cid}")
        reference = gray(REPO / case["reference"])
        for lib in LIBRARIES:
            row = rows[cid, lib]
            if row["reference_ink"] != int(np.count_nonzero(reference < 128)):
                raise ValueError(f"Stale reference ink: {cid}/{lib}")
            if row["status"] == "error":
                if not row.get("error"):
                    raise ValueError(f"Missing error diagnostic: {cid}/{lib}")
                if row["score"] != (0.0 if row["reference_ink"] else None):
                    raise ValueError(f"Stale error score: {cid}/{lib}")
                continue
            if row["status"] not in {"rendered", "blank"}:
                raise ValueError(f"Unknown render status: {cid}/{lib}")
            raster = gray(dest / "images" / f"{cid}-{lib}.png")
            metrics, diff = compare(reference, raster)
            for key, value in metrics.items():
                if row[key] != value:
                    raise ValueError(f"Stale {key}: {cid}/{lib}")
            expected_score = metrics["iou"] if row["reference_ink"] else None
            expected_status = "rendered" if metrics["output_ink"] else "blank"
            if row["score"] != expected_score or row["status"] != expected_status:
                raise ValueError(f"Stale score/status: {cid}/{lib}")
            with Image.open(dest / "images" / f"{cid}-{lib}-diff.png") as image:
                if not np.array_equal(np.asarray(image.convert("RGB")), diff):
                    raise ValueError(f"Stale difference image: {cid}/{lib}")
    return rows


def status(row):
    if row["status"] == "error":
        return "Render error"
    if row["score"] is None:
        return "Blank printer reference; unscored"
    return (
        f"{row['score'] * 100:.1f}% IoU"
        + (" · exact" if row["exact"] else "")
        + (" · blank output" if row["status"] == "blank" else "")
    )


def pages(data, dest):
    rows = validate(data, dest)
    cases = data["cases"]
    groups = sorted({c["group"] for c in cases})
    result = {}
    banner = "<!-- Generated by benchmarks/accuracy/gallery.py. -->\n\n"
    legend = "Black = matching ink; magenta = printer only; cyan = library only. Images retain their original pixels; click an image to inspect it at full size."
    nav = "[All comparisons](../README.md) · [Accuracy scores](../../README.md)"
    index = [
        "# Library renders versus printer previews",
        f"{len(cases)} captured cases × {len(LIBRARIES)} renderers = {len(rows)} recorded attempts. Measured {data['measured_utc']}.",
        "Choose a library or case to see the **printer preview, library render, and difference image together**. Render errors include diagnostics; blank outputs remain visible.",
        legend,
        "[Accuracy scores and methodology](../README.md)",
        "## By library",
        table(
            ["Library", "Attempts", "Render errors"],
            [
                [
                    f"[{NAMES[lib]}](libraries/{lib}.md)",
                    len(cases),
                    sum(rows[c["id"], lib]["status"] == "error" for c in cases),
                ]
                for lib in LIBRARIES
            ],
        ),
    ]
    for group in groups:
        index += [
            f"## {group}",
            table(
                ["Case", "Command", "Arguments"],
                [
                    [
                        f"[{c['name']}](cases/{c['id']}.md)",
                        c["command"],
                        c["arguments"].replace("|", "/"),
                    ]
                    for c in cases
                    if c["group"] == group
                ],
            ),
        ]
    result[Path("comparisons/README.md")] = banner + "\n\n".join(index) + "\n"
    for lib in LIBRARIES:
        content = [
            f"# {NAMES[lib]} versus printer previews",
            nav,
            f"All {len(cases)} cases were attempted. Select a case to compare images and inspect any error.",
        ]
        for group in groups:
            content += [
                f"## {group}",
                table(
                    ["Compare images", "Result", "Arguments"],
                    [
                        [
                            f"[{c['name']}](../cases/{c['id']}.md#{lib})",
                            status(rows[c["id"], lib]),
                            c["arguments"].replace("|", "/"),
                        ]
                        for c in cases
                        if c["group"] == group
                    ],
                ),
            ]
        result[Path(f"comparisons/libraries/{lib}.md")] = (
            banner + "\n\n".join(content) + "\n"
        )
    for case in cases:
        cid = case["id"]
        page = dest / "comparisons/cases" / f"{cid}.md"
        reference = os.path.relpath(REPO / case["reference"], page.parent)
        source = os.path.relpath(REPO / case["zpl"], page.parent)
        with Image.open(REPO / case["reference"]) as image:
            ref_width, ref_height = image.size
        content = [
            f"# {case['name']}",
            nav,
            f"**{case['command']}** · {case['arguments']} · [ZPL input]({source}) · [Printer preview]({reference})",
            f"Measured {data['measured_utc']}. Printer capture metadata is recorded in [results.json](../../results.json).",
            legend,
            " · ".join(f"[{NAMES[lib]}](#{lib})" for lib in LIBRARIES),
        ]
        for lib in LIBRARIES:
            row = rows[cid, lib]
            content += [
                f"## {lib}",
                f"**{NAMES[lib]}: {status(row)}** · [All cases for this library](../libraries/{lib}.md)",
            ]
            printer = f"![Printer preview]({reference})"
            if row["status"] == "error":
                content += [
                    table(
                        ["Printer preview", "Library render", "Difference"],
                        [[printer, "Render failed; no image", "Unavailable"]],
                    ),
                    "Error diagnostic:",
                    "~~~text\n" + row["error"].replace("~~~", "~ ~ ~") + "\n~~~",
                ]
            else:
                width, height = row["output_dimensions"]
                content += [
                    f"Printer: {ref_width} × {ref_height} dots; library: {width} × {height} dots. Missing ink: {row['missing']} pixels; extra ink: {row['extra']} pixels.",
                    table(
                        ["Printer preview", "Library render", "Difference"],
                        [
                            [
                                printer,
                                f"![{lib} render](../../images/{cid}-{lib}.png)",
                                f"![{lib} difference](../../images/{cid}-{lib}-diff.png)",
                            ]
                        ],
                    )
                ]
        result[Path(f"comparisons/cases/{cid}.md")] = (
            banner + "\n\n".join(content) + "\n"
        )
    return result


def generate(dest, check=False):
    data = json.loads((dest / "results.json").read_text())
    generated = pages(data, dest)
    for relative, content in generated.items():
        path = dest / relative
        if check:
            if not path.is_file() or path.read_text() != content:
                raise ValueError(f"Out of date: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(
        f"Verified {len(data['results'])} render attempts and their artifacts; {'checked' if check else 'generated'} {len(generated)} comparison pages"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generate(args.output, args.check)
