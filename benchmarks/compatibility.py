#!/usr/bin/env python3
"""Generate both directions of the ZPL compatibility reference, offline with stdlib.

Source handlers, upstream claims, execution and printer fidelity are separate axes.
Inputs: command-support.json, argument-support.md, accuracy/results.json and the
conformance manifest; optional docs/benchmarks/conformance/results.json.
"""

import argparse
from collections import Counter
import hashlib
import json
import os
from pathlib import Path
import re
import statistics
import tomllib
import xml.etree.ElementTree as ET

REPO = Path(__file__).resolve().parent.parent
DEST = REPO / "docs/compatibility"
SUPPORT = REPO / "docs/benchmarks/command-support.json"
ACCURACY = REPO / "docs/benchmarks/accuracy/results.json"
CORPUS = REPO / "test-data/render-conformance/manifest.json"
CONFORMANCE = REPO / "docs/benchmarks/conformance/results.json"
NOTES = REPO / "docs/benchmarks/argument-support.md"
LIBRARIES = {
    "codyps-zpl": ("codyps/zpl", "Rust", "Parser and renderer"),
    "toolchain": ("zpl-toolchain", "Rust", "Parser and validator"),
    "labelize": ("labelize", "Rust", "Parser and renderer"),
    "forge": ("zpl-forge", "Rust", "Parser and renderer"),
    "go": ("go-zpl", "Go", "Parser and renderer"),
    "ffi": ("zpl-rs", "Rust → Go", "Renderer wrapper"),
    "binarykits": ("BinaryKits.Zpl Viewer", ".NET", "Parser and renderer"),
    "zplr": ("ZPLr", "TypeScript", "Parser and renderer"),
    "builder": ("zpl-builder", "Rust", "Typed generator"),
    "python": ("Python ZPL", "Python", "Typed generator"),
    "jszpl": ("JSZPL", "TypeScript", "Typed generator"),
    "labelary": ("Labelary", "Hosted service", "Captured renderer"),
}
RENDERERS = {"codyps-zpl", "labelize", "forge", "go", "ffi", "binarykits", "zplr", "labelary"}
LABELS = {
    "D": "🧩 Handler found",
    "I": "⏭️ Ignored / stored only",
    "F": "📦 Framing only",
    "T": "📐 Specification table",
    "E": "🛠️ Typed emission",
    "S": "🟢 Upstream: supported",
    "P": "🟡 Upstream: partial",
    "U": "🔴 Upstream: unsupported",
    "N": "⚪ Upstream: non-rendering",
    "?": "❔ No evidence found",
}
BANNER = "<!-- Generated by benchmarks/compatibility.py. Edit the inputs, then regenerate. -->\n\n"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load(path):
    return json.loads(path.read_text())


def command_slug(command):
    # Prefix and @ must survive normalization: ^CC != ~CC, ^A != ^A@.
    if not re.fullmatch(r"[\^~][A-Z][A-Z0-9@]?", command):
        raise ValueError(command)
    return ("format-" if command[0] == "^" else "control-") + command[1:].replace(
        "@", "-named"
    ).lower()


def href(page, target):
    return os.path.relpath(target, page.parent).replace(os.sep, "/")


def link(page, target, label, anchor=None):
    suffix = f"#{anchor}" if anchor else ""
    return f"[{label}]({href(page, target)}{suffix})"


def table(headers, rows):
    def cell(x):
        return str(x).replace("|", "&#124;").replace("\n", " ")

    return (
        "\n".join(
            [
                "| " + " | ".join(map(cell, headers)) + " |",
                "| " + " | ".join("---" for _ in headers) + " |",
                *["| " + " | ".join(map(cell, row)) + " |" for row in rows],
            ]
        )
        + "\n"
    )


def state(support, library, command):
    return (
        support["commands"][library]
        .get(command, {})
        .get("status", "F" if library == "codyps-zpl" else "?")
    )


def evidence(page, support, library, command):
    status = state(support, library, command)
    source = support["commands"][library].get(command, {}).get("source")
    if source and not source.startswith(("https://", "http://")):
        path, sep, fragment = source.partition("#")
        source = href(page, (SUPPORT.parent / path).resolve()) + (
            sep + fragment if sep else ""
        )
    return f"[{LABELS[status]}]({source})" if source else LABELS[status]


def accuracy_summary(library, rows):
    if library not in RENDERERS:
        return "N/A – no incoming-ZPL renderer"
    samples = [r for r in rows if r["library"] == library and r["score"] is not None]
    blank = sum(r["library"] == library and r["score"] is None for r in rows)
    if not samples:
        return "Not measured" if not blank else f"{blank} blank references; unscored"
    exact = sum(r.get("exact", False) for r in samples)
    failures = sum(r["status"] == "error" for r in samples)
    return f"{exact}/{len(samples)} exact; mean IoU {statistics.mean(r['score'] for r in samples) * 100:.1f}%; {failures} errors"


def execution_summary(library, rows):
    if library not in RENDERERS:
        return "N/A – no incoming-ZPL renderer"
    selected = [r for r in rows if r["library"] == library]
    counts = Counter(r["status"] for r in selected if r["validity"] != "invalid")
    negative = Counter(r["status"] for r in selected if r["validity"] == "invalid")
    text = ", ".join(f"{n} {status}" for status, n in sorted(counts.items()))
    if negative:
        text += (
            ("; " if text else "")
            + "Negative-input observations: "
            + ", ".join(f"{n} {status}" for status, n in sorted(negative.items()))
        )
    return text or "Not measured"


def library_versions(support):
    rust = tomllib.loads((REPO / "benchmarks/adapters/rust/Cargo.toml").read_text())[
        "dependencies"
    ]
    node = load(REPO / "benchmarks/adapters/node/package.json")["dependencies"]
    versions = {
        key: rust[key]["version"].lstrip("=")
        for key in ["toolchain", "labelize", "forge", "ffi", "builder"]
    }
    versions["codyps-zpl"] = support["sources"]["zpl"]["version"] + " @ " + support["sources"]["zpl"]["rev"][:12]

    versions.update({n: node[n] for n in ["zplr", "jszpl"]})
    for key, source in [("go", "go-zpl"), ("python", "python-zpl")]:
        versions[key] = "source " + support["sources"][source]["rev"][:12]
    root = ET.parse(REPO / "benchmarks/adapters/dotnet/Comparison.csproj").getroot()
    versions["binarykits"] = next(
        e.attrib["Version"].strip("[]")
        for e in root.iter("PackageReference")
        if e.attrib["Include"] == "BinaryKits.Zpl.Viewer"
    )
    capture = load(REPO / "docs/benchmarks/labelary/captures.json")
    exposed = sorted({c["renderer_version"] for c in capture["cases"] if c["renderer_version"]})
    versions["labelary"] = "captured " + capture["started_utc"] + " (" + (", ".join(exposed) if exposed else "build version not exposed") + ")"
    return versions


def notes(page):
    # One maintained argument-limit table; fail rather than silently misassign rows.
    body = NOTES.read_text().split("| Library / API |", 1)[1].split("\n\n", 1)[0]
    rows = [
        line
        for line in body.splitlines()
        if line.startswith("| ") and not line.startswith("| ---")
    ]
    if len(rows) != len(LIBRARIES):
        raise ValueError("Argument notes table changed; update library mapping")
    result = {}
    for library, row in zip(LIBRARIES, rows, strict=True):
        parts = row.strip("|").split("|")
        expected = LIBRARIES[library][0].removesuffix(" Viewer")
        if not parts[0].strip().startswith(expected):
            raise ValueError(f"Argument notes reordered: expected {expected}")
        text = " ".join(p.strip() for p in parts[1:])

        def rewrite(match):
            label, url = match.groups()
            return (
                match[0]
                if "://" in url
                else link(page, (NOTES.parent / url).resolve(), label)
            )

        result[library] = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", rewrite, text)
    return result


def validate_accuracy(data):
    cases = {c["id"]: c for c in data["cases"]}
    if len(cases) != len(data["cases"]):
        raise ValueError("Duplicate accuracy case")
    for case in cases.values():
        if (
            digest(REPO / case["zpl"]) != case["zpl_sha256"]
            or digest(REPO / case["reference"]) != case["png_sha256"]
        ):
            raise ValueError("Stale accuracy source/reference hash")
    seen = set()
    for row in data["results"]:
        key = row["library"], row["case"]
        if key in seen or row["case"] not in cases or row["library"] not in RENDERERS:
            raise ValueError("Invalid/duplicate accuracy result")
        seen.add(key)
    return cases


def artifacts(dest=DEST):
    support = load(SUPPORT)
    accuracy = load(ACCURACY)
    corpus = load(CORPUS)
    commands = dict(
        line.split("\t")
        for line in (REPO / "docs/zpl-command-index.tsv").read_text().splitlines()
        if line.startswith(("^", "~"))
    )
    if set(support["commands"]) != set(LIBRARIES):
        raise ValueError("Library catalog and support inventory differ")
    acases = validate_accuracy(accuracy)
    for case in corpus["cases"]:
        if digest(CORPUS.parent / case["file"]) != case["sha256"]:
            raise ValueError("Stale conformance case hash")
    conformance = load(CONFORMANCE) if CONFORMANCE.exists() else None
    if conformance and conformance["manifest_sha256"] != digest(CORPUS):
        raise ValueError("Stale conformance results: regenerate against current corpus")
    execution = conformance["results"] if conformance else []
    corpus_cases = {c["name"]: c for c in corpus["cases"]}
    seen = set()
    for row in execution:
        key = row["library"], row["case"]
        case = corpus_cases.get(row["case"])
        if key in seen or row["library"] not in RENDERERS or not case:
            raise ValueError("Invalid/duplicate conformance result")
        if row["validity"] != case["validity"] or row["group"] != case["group"]:
            raise ValueError("Conformance case classification mismatch")
        seen.add(key)
    versions = library_versions(support)
    groups = sorted({c["group"] for c in corpus["cases"]})
    files = {}

    def command_path(cmd):
        return dest / "commands" / (command_slug(cmd) + ".md")

    def library_path(lib):
        return dest / "libraries" / (lib + ".md")

    def feature_path(group):
        return dest / "features" / (group + ".md")

    def name(cmd):
        return support.get("descriptions", {}).get(cmd, {}).get("name", cmd)

    def title(group):
        return group.replace("-", " ").capitalize()

    def nav(page):
        return (
            " · ".join(
                link(page, dest / x, label)
                for x, label in [
                    ("README.md", "Overview"),
                    ("libraries/README.md", "Libraries"),
                    ("commands/README.md", "Commands"),
                    ("features/README.md", "Features"),
                    ("METHODOLOGY.md", "Evidence legend"),
                ]
            )
            + " · "
            + link(page, ACCURACY.parent / "comparisons/README.md", "Compare images")
            + "\n"
        )

    def emit(page, text):
        files[str(page.relative_to(dest))] = (
            BANNER + "\n\n".join(text) + "\n"
        ).encode()

    def related_cases(ids):
        return [r for r in accuracy["results"] if r["case"] in ids]

    def focused(cmd):
        return {c["id"] for c in accuracy["cases"] if c["command"] == cmd}

    def feature_measurements(group):
        cases = [c for c in corpus["cases"] if c["group"] == group]
        hashes = {c["sha256"] for c in cases if c["validity"] != "invalid"}
        ids = {cid for cid, c in acases.items() if c["zpl_sha256"] in hashes}
        return cases, related_cases(ids)

    def accuracy_details(page, ids, library=None):
        rows = []
        for cid in sorted(ids):
            c = acases[cid]
            values = []
            for lib in [library] if library else LIBRARIES:
                matches = [
                    r
                    for r in accuracy["results"]
                    if r["case"] == cid and r["library"] == lib
                ]
                if not matches:
                    values.append("N/A" if lib not in RENDERERS else "Not measured")
                    continue
                r = matches[0]
                if r["score"] is None:
                    label_text = "Blank reference; unscored"
                elif r["status"] == "error":
                    label_text = "Error"
                else:
                    label_text = f"{r['score'] * 100:.1f}% IoU" + (
                        " · exact" if r.get("exact") else ""
                    )
                values.append(
                    link(
                        page,
                        ACCURACY.parent / "comparisons/cases" / f"{cid}.md",
                        label_text,
                        anchor=lib,
                    )
                )
            rows.append(
                [
                    link(page, REPO / c["zpl"], c["name"]),
                    c["arguments"],
                    link(page, REPO / c["reference"], "Printer"),
                    *values,
                ]
            )
        return (
            table(
                [
                    "Case",
                    "Arguments",
                    "Reference",
                    *(
                        [LIBRARIES[library][0]]
                        if library
                        else [v[0] for v in LIBRARIES.values()]
                    ),
                ],
                rows,
            )
            if rows
            else "No focused printer measurements yet."
        )

    def fixture_table(page, cases, limit=None):
        selected = cases if limit is None else cases[:limit]
        text = table(
            ["Fixture", "Classification", "Purpose"],
            [
                [
                    link(page, CORPUS.parent / c["file"], c["name"]),
                    c["validity"] + " / " + c["oracle"],
                    c["purpose"],
                ]
                for c in selected
            ],
        )
        if len(selected) < len(cases):
            text += (
                f"\nShowing {len(selected)} of {len(cases)} occurrences; "
                + link(page, CORPUS, "complete manifest")
                + ". Occurrence includes setup commands and is not a focused test of every listed command.\n"
            )
        return text

    page = dest / "README.md"
    emit(
        page,
        [
            "# ZPL compatibility",
            nav(page),
            "Browse ZPL support by library or by command/feature. These are GitHub-native Markdown pages generated from the same evidence, not separate hand-maintained lists.",
            f"**{len(LIBRARIES)} libraries · {len(commands)} command spellings · {len(groups)} feature groups · {len(corpus['cases'])} fixtures.**",
            table(
                ["Browse", "Contents"],
                [
                    [
                        link(page, dest / "libraries/README.md", "By library"),
                        "Versions, argument limits, every command and feature, measured examples",
                    ],
                    [
                        link(page, dest / "commands/README.md", "By command"),
                        "Cross-library evidence, reference parameters and focused printer comparisons",
                    ],
                    [
                        link(page, dest / "features/README.md", "By feature"),
                        "Combined behavior, fixture lists, matched printer evidence and execution results",
                    ],
                ],
            ),
            "**Read the evidence labels.** A handler, typed emitter or upstream support claim does not establish complete argument support or printer fidelity. “Not measured” is not “unsupported”. Rendering accuracy is N/A for generators and parser-only APIs.",
            f"Printer measurements: **{accuracy['measured_utc']}**, {accuracy['fresh_reference']['device']}, firmware {accuracy['fresh_reference']['firmware']}. Historical measurements are not rerun by document generation.",
            (
                f"Conformance execution: **{conformance['measured_utc']}**. "
                + link(page, CONFORMANCE, "Raw execution results")
                + "; execution is not a printer-fidelity score."
            )
            if conformance
            else "No saved conformance execution results. Untested features remain explicitly unmeasured.",
            "Regenerate offline with `python3 benchmarks/compatibility.py`; verify with `python3 benchmarks/compatibility.py --check`. GitHub Actions refreshes these pages after rebuilding the evidence and running benchmarks. The repository README links to this reference.",
            link(page, dest / "inputs.json", "Input hashes and provenance")
            + " · "
            + link(page, REPO / "benchmarks/README.md", "Run benchmarks"),
        ],
    )
    emit(
        dest / "METHODOLOGY.md",
        [
            "# Interpreting compatibility evidence",
            nav(dest / "METHODOLOGY.md"),
            table(
                ["Label", "Meaning"],
                [
                    [LABELS[k], v]
                    for k, v in {
                        "D": "Explicit parser/render-path handler. Parameters may be ignored, rejected or approximate.",
                        "I": "Recognized but skipped or stored without the relevant raster effect.",
                        "F": "codyps/zpl framer preserves bytes; no codyps/zpl rendering handler found.",
                        "T": "Schema/table-driven parsing or validation; not a pixel renderer.",
                        "E": "Typed generation path; not incoming-ZPL interpretation.",
                        "S": "Upstream catalog claims support; not independent certification.",
                        "P": "Upstream catalog explicitly claims partial support.",
                        "U": "Upstream catalog explicitly marks unsupported.",
                        "N": "Upstream classifies as non-rendering; does not mean every device operation is implemented.",
                        "?": "No evidence in selected entry points. Generic/dynamic paths may exist.",
                    }.items()
                ],
            ),
            "Each library/command cell is generated once conceptually and presented in both directions. Colors describe evidence categories, not a universal yes/no score. The inventory includes device/storage commands for completeness, but the rendering corpus excludes those operations.",
            "Command printer results use the case’s explicitly identified target command, never every incidental setup command. Feature results reuse historical printer measurements only when source SHA-256 matches exactly. Conformance execution results, when present, must match the current manifest hash. No execution result is upgraded to a support claim.",
            "Exact means identical thresholded ink and dimensions. IoU is foreground intersection/union without alignment or scaling. Errors score zero for nonblank references; blank references are unscored. The archived barcode set is development data, not a holdout. Different valid barcode encodings may produce different pixels. This measures printer HTTP previews, not physical print quality.",
            "Source inventory and pinned library revisions may be newer than saved measurements. Dates and input hashes are exposed; generation validates input/reference bytes but does not prove the current compiled renderer matches an older run. Results are a pinned snapshot, not a browser-style version history.",
            "Feature groups follow the conformance corpus categories. Negative inputs have no valid-label fidelity score. Font-dependent cases require attention to installed resident fonts. Test presence is not support.",
            "Generated pages are refreshed in CI and included in its artifact; CI does not commit them automatically. To publish a refreshed baseline, run the generator locally after updating measured inputs and commit the generated pages with those inputs.",
        ],
    )

    page = dest / "libraries/README.md"
    emit(
        page,
        [
            "# Libraries",
            nav(page),
            table(
                [
                    "Library",
                    "Language",
                    "API category",
                    "Version / pin",
                    "Printer measurements",
                ],
                [
                    [
                        link(page, library_path(lib), meta[0]),
                        meta[1],
                        meta[2],
                        versions[lib],
                        accuracy_summary(lib, accuracy["results"]),
                    ]
                    for lib, meta in LIBRARIES.items()
                ],
            ),
        ],
    )
    page = dest / "commands/README.md"
    emit(
        page,
        [
            "# Commands",
            nav(page),
            "Find a command by mnemonic or description. Format (`^`) and control (`~`) variants have separate pages.",
            table(
                ["Command", "Feature", "Reference parameters", "Focused printer cases"],
                [
                    [
                        link(page, command_path(cmd), f"`{cmd}`"),
                        name(cmd),
                        ", ".join(support["parameter_keys"].get(cmd, [])) or "–",
                        len(focused(cmd)),
                    ]
                    for cmd in commands
                ],
            ),
        ],
    )
    page = dest / "features/README.md"
    emit(
        page,
        [
            "# Features",
            nav(page),
            "Feature groups are rendering behaviors tested by the corpus, including combined pages and negative inputs.",
            table(
                ["Feature", "Fixtures", "Libraries with matched printer measurements"],
                [
                    [
                        link(page, feature_path(g), title(g)),
                        len(feature_measurements(g)[0]),
                        len({r["library"] for r in feature_measurements(g)[1]}),
                    ]
                    for g in groups
                ],
            ),
        ],
    )

    for lib, meta in LIBRARIES.items():
        page = library_path(lib)
        rows = [
            [
                link(page, command_path(cmd), f"`{cmd}`"),
                name(cmd),
                evidence(page, support, lib, cmd),
                accuracy_summary(lib, related_cases(focused(cmd))),
            ]
            for cmd in commands
        ]
        feature_rows = []
        for group in groups:
            cases, measured = feature_measurements(group)
            ids = {c["name"] for c in cases}
            feature_rows.append(
                [
                    link(page, feature_path(group), title(group)),
                    len(cases),
                    accuracy_summary(lib, measured),
                    execution_summary(lib, [r for r in execution if r["case"] in ids]),
                ]
            )
        emit(
            page,
            [
                f"# {meta[0]}",
                nav(page),
                f"**{meta[1]} · {meta[2]} · {versions[lib]}**",
                "## Argument limits",
                notes(page)[lib],
                link(page, NOTES, "Maintained argument review and sources"),
                "## Measured rendering",
                link(
                    page,
                    ACCURACY.parent / "comparisons/libraries" / f"{lib}.md",
                    "Compare this library's renders with printer previews",
                )
                if lib in RENDERERS
                else "This library does not render incoming ZPL.",
                accuracy_summary(lib, accuracy["results"])
                + f". Snapshot: {accuracy['measured_utc']}.",
                "## Feature groups",
                table(
                    [
                        "Feature",
                        "Fixtures",
                        "Printer evidence",
                        "Conformance execution",
                    ],
                    feature_rows,
                ),
                "## Command support",
                table(
                    ["Command", "Name", "Source evidence", "Focused printer evidence"],
                    rows,
                ),
            ],
        )

    for cmd, pdf_page in commands.items():
        page = command_path(cmd)
        ids = focused(cmd)
        cases = [c for c in corpus["cases"] if cmd in c["commands"]]
        params = support["parameter_keys"].get(cmd, [])
        rows = [
            [
                link(page, library_path(lib), meta[0]),
                versions[lib],
                evidence(page, support, lib, cmd),
                accuracy_summary(lib, related_cases(ids)),
                f"[Argument limits]({href(page, library_path(lib))}#argument-limits)",
            ]
            for lib, meta in LIBRARIES.items()
        ]
        related = sorted({c["group"] for c in cases})
        emit(
            page,
            [
                f"# `{cmd}` – {name(cmd)}",
                nav(page),
                support.get("descriptions", {})
                .get(cmd, {})
                .get("description", "See the command reference."),
                f"Reference parameters: **{', '.join(params) if params else 'not cataloged'}**. These describe the reference grammar, not a promise that any library honors every parameter. "
                + link(
                    page,
                    REPO / "docs/zpl-zbi2-pg-en.pdf",
                    f"Zebra guide, page {pdf_page}",
                )
                + ".",
                "## Library comparison",
                table(
                    [
                        "Library",
                        "Version / pin",
                        "Source evidence",
                        "Focused printer evidence",
                        "Caveats",
                    ],
                    rows,
                ),
                "## Tested arguments and pixels",
                accuracy_details(page, ids),
                "## Related features",
                " · ".join(link(page, feature_path(g), title(g)) for g in related)
                or "No rendering corpus cases; this may be a device/storage command outside rendering scope.",
                "## Corpus occurrences",
                fixture_table(page, cases, 20)
                if cases
                else "No fixture. No support conclusion can be drawn from absence.",
            ],
        )

    for group in groups:
        page = feature_path(group)
        cases, measured = feature_measurements(group)
        cmds = sorted({cmd for c in cases for cmd in c["commands"]})
        ids = {c["name"] for c in cases}
        rows = []
        for lib, meta in LIBRARIES.items():
            counts = Counter(state(support, lib, cmd) for cmd in cmds)
            tally = "; ".join(f"{n} {LABELS[k]}" for k, n in sorted(counts.items()))
            rows.append(
                [
                    link(page, library_path(lib), meta[0]),
                    tally,
                    accuracy_summary(lib, measured),
                    execution_summary(lib, [r for r in execution if r["case"] in ids]),
                ]
            )
        emit(
            page,
            [
                f"# {title(group)}",
                nav(page),
                f"{len(cases)} fixtures. Command occurrence counts include setup commands and are not a feature pass rate. Source and execution evidence must be read separately.",
                "## Library comparison",
                table(
                    [
                        "Library",
                        "Evidence for commands present",
                        "Matched printer evidence",
                        "Conformance execution",
                    ],
                    rows,
                ),
                "## Commands involved",
                " · ".join(link(page, command_path(cmd), f"`{cmd}`") for cmd in cmds),
                "## Matched printer cases",
                accuracy_details(page, {r["case"] for r in measured}),
                "## Fixtures",
                fixture_table(page, cases),
            ],
        )
    inputs = [
        SUPPORT,
        ACCURACY,
        CORPUS,
        NOTES,
        REPO / "docs/zpl-command-index.tsv",
        REPO / "benchmarks/adapters/rust/Cargo.toml",
        REPO / "benchmarks/adapters/node/package.json",
        REPO / "benchmarks/adapters/dotnet/Comparison.csproj",
        REPO / "benchmarks/sources.lock.json",
        Path(__file__),
    ]
    if conformance:
        inputs.append(CONFORMANCE)
    provenance = {
        "schema": 1,
        "inputs": {str(p.relative_to(REPO)): digest(p) for p in inputs},
        "accuracy_measured_utc": accuracy["measured_utc"],
        "conformance_measured_utc": conformance.get("measured_utc")
        if conformance
        else None,
        "libraries": versions,
        "command_pages": len(commands),
        "feature_pages": len(groups),
    }
    files["inputs.json"] = (json.dumps(provenance, indent=2) + "\n").encode()
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--output", type=Path, default=DEST)
    args = ap.parse_args()
    generated = artifacts(args.output.resolve())
    stale = {
        str(p.relative_to(args.output))
        for p in args.output.rglob("*.md")
        if p.read_text().startswith(BANNER)
    } - set(generated)
    if args.check and stale:
        raise SystemExit(f"Stale pages: {sorted(stale)}")
    for name in stale:
        (args.output / name).unlink()  # Only files bearing this generator's marker.
    for name, data in generated.items():
        path = args.output / name
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f"Out of date: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(
        f"{'Verified' if args.check else 'Generated'} {len(generated) - 1} Markdown pages"
    )


if __name__ == "__main__":
    main()
