#!/usr/bin/env python3
"""Regenerate GitHub Markdown and static plots using only saved results.json."""

import json
import os
from pathlib import Path
import sys

os.environ.setdefault(
    "MPLCONFIGDIR", str(Path(__file__).resolve().parent / "_work/matplotlib")
)
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from formatting import NAMES, table


def main():
    dest = Path(sys.argv[1])
    part = sys.argv[2] if len(sys.argv) > 2 else "all"
    data = json.loads((dest / "results.json").read_text())
    ok = [r for r in data["results"] if r["status"] == "ok"]
    plt.rcParams.update(
        {
            "font.size": 10,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "svg.hashsalt": "zpl-comparison",
        }
    )
    for mode in [m for m in ["parse", "png", "generate"] if part in ["all", m]]:
        fixtures = sorted({r["fixture"] for r in ok if r["mode"] == mode})
        if not fixtures:
            continue
        fig, axes = plt.subplots(
            len(fixtures),
            1,
            figsize=(10, max(3, len(fixtures) * 2.8)),
            squeeze=False,
            layout="constrained",
        )
        for ax, fixture in zip(axes[:, 0], fixtures):
            rows = sorted(
                [r for r in ok if r["mode"] == mode and r["fixture"] == fixture],
                key=lambda r: r["median_ns"],
            )
            values = [r["median_ns"] / 1e3 for r in rows]
            ax.barh(
                [NAMES[r["library"]] for r in rows],
                values,
                color=[
                    "#1967a3" if r["library"] == "codyps-zpl" else "#728da5" for r in rows
                ],
            )
            ax.errorbar(
                values,
                range(len(rows)),
                xerr=[
                    [max(0, r["median_ns"] - r["min_ns"]) / 1e3 for r in rows],
                    [max(0, r["max_ns"] - r["median_ns"]) / 1e3 for r in rows],
                ],
                fmt="none",
                ecolor="#222",
                capsize=2,
            )
            ax.invert_yaxis()
            ax.set_xscale("log")
            ax.set_xlabel("µs / operation (log scale)")
            ax.set_title(fixture)
        fig.suptitle(
            {
                "parse": "Parse API cost – different output contracts",
                "png": "Parse + rasterize + encode PNG – native defaults",
                "generate": "Construct + serialize text label – different builders",
            }[mode]
        )
        fig.savefig(dest / f"{mode}.svg", metadata={"Date": None})
        fig.savefig(dest / f"{mode}.png", dpi=110)
        plt.close(fig)
    if part in ["all", "memory"]:
        names = sorted(
            {r["library"] for r in ok},
            key=lambda n: max(r["peak_rss_bytes"] for r in ok if r["library"] == n),
        )
        fig, ax = plt.subplots(figsize=(10, 5), layout="constrained")
        ax.barh(
            [NAMES[n] for n in names],
            [
                max(r["peak_rss_bytes"] for r in ok if r["library"] == n) / 2**20
                for n in names
            ],
            color="#728da5",
        )
        ax.set_xlabel("MiB; maximum child peak RSS across measured workloads")
        ax.set_title("Process memory includes runtime, warm-up and output capture")
        fig.savefig(dest / "memory.svg", metadata={"Date": None})
        plt.close(fig)
    if part in ["all", "size"]:
        names = [n for n in data["sizes"] if "artifact_bytes" in data["sizes"][n]]
        fig, axes = plt.subplots(1, 2, figsize=(13, 5), layout="constrained")
        for ax, field, title in zip(
            axes,
            ["bytes", "artifact_bytes"],
            ["Selected source bytes", "Adapter + deployed files (runtime excluded)"],
        ):
            ax.barh(
                [NAMES[n] for n in names],
                [data["sizes"][n][field] / 1024 for n in names],
                color="#728da5",
            )
            ax.set_xscale("log")
            ax.set_xlabel("KiB (log scale)")
            ax.set_title(title)
        fig.savefig(dest / "size.svg", metadata={"Date": None})
        plt.close(fig)
    if part not in ["all", "markdown"]:
        return
    text = [
        "# ZPL library benchmark\n",
        "Generated by [`benchmarks/report.py`](../../benchmarks/report.py). "
        "[Methodology and reproduction](../../benchmarks/README.md) · [Capabilities and selection](capabilities.md) · [Commands and arguments](command-support.md) · [Compare printer and library images](accuracy/README.md) · [Raw measurements](results.json).\n",
        f"Measured **{data['timestamp_utc']}**, `{data['host']['platform']}`, `{data['host']['machine']}`. "
        f"codyps/zpl revision `{data['git_revision']}`; working tree dirty: `{data['git_dirty']}`. "
        f"{data['samples']} fresh processes per cell, ≥250 ms and ≥3 warm-up operations per process; calibrated batches target {data['target_seconds']} s.\n",
        "These are API costs on synthetic labels, **not a universal speed ranking or printer-fidelity certification**. "
        "Streaming framing, AST parsing and scene construction perform different work. PNG encoders, fonts, antialiasing and compression use library defaults. "
        "Builders construct labels and cannot substitute for a renderer. No network/printer calls are timed.\n",
        "## Findings from this run\n",
    ]
    for mode in ["parse", "png", "generate"]:
        rows = [r for r in ok if r["mode"] == mode]
        if not rows:
            continue
        fixture = "text" if mode != "generate" else "fields-48"
        group = sorted(
            [r for r in rows if r["fixture"] == fixture], key=lambda r: r["median_ns"]
        )
        if group:
            first = group[0]
            last = group[-1]
            text.append(
                f"- `{mode}` / `{fixture}`: {NAMES[first['library']]} has the lowest measured median ({first['median_ns'] / 1e3:.2f} µs); the range across successful adapters is {last['median_ns'] / first['median_ns']:.1f}×. This comparison is limited by the contracts above.\n"
            )
    failed = [r for r in data["results"] if r["status"] != "ok"]
    text.append(
        f"- {len(ok)} successful cells; {len(failed)} failed cells. Failed cells are excluded from timing plots and retained below.\n"
    )
    comparisons = []
    for r in sorted(
        [r for r in ok if r["library"] == "codyps-zpl" and r["mode"] == "png"],
        key=lambda r: r["fixture"],
    ):
        peers = [
            p
            for p in ok
            if p["mode"] == "png"
            and p["fixture"] == r["fixture"]
            and p["library"] != "codyps-zpl"
        ]
        if not peers:
            continue
        best = min(peers, key=lambda p: p["median_ns"])
        comparisons.append(
            [
                r["fixture"],
                f"{r['median_ns'] / 1e3:.1f}",
                NAMES[best["library"]],
                f"{best['median_ns'] / 1e3:.1f}",
                f"{r['median_ns'] / best['median_ns']:.2f}×",
            ]
        )
    if comparisons:
        text += [
            "\ncodyps/zpl versus the lowest-latency other PNG adapter for each fixture (ratio below 1 means codyps/zpl was faster):\n",
            table(
                [
                    "Fixture",
                    "codyps/zpl µs",
                    "Lowest other median",
                    "Other µs",
                    "This / other",
                ],
                comparisons,
            ),
            "The parser result and PNG result should be read separately: a cheap command framer does not imply a cheap rasterizer or PNG encoder. "
            "For identical geometry, the boxes row is the strongest correctness-controlled comparison here; text and barcode renderings can differ.\n",
        ]
    text += [
        "\n## Capabilities exercised\n",
        "PNG checks require a decodable 400×300 image with both light and dark pixels. Only `boxes` has an exact geometric oracle; "
        "text/barcode checks establish nonblank output, **not correct content or decodability**. Inspect the captured PNGs before choosing a renderer. "
        "A successful parse means the API completed, not that it recognized or preserved every command.\n",
    ]
    renderers = [
        n
        for n, modes in __import__("run").MODES.items()
        if "png" in modes and any(r["library"] == n for r in data["results"])
    ]
    fixtures = ["boxes", "text", "code128", "qr", "dense"]
    rows = []
    for n in renderers:
        cells = []
        for f in fixtures:
            r = next(
                (
                    r
                    for r in data["results"]
                    if r["library"] == n and r["mode"] == "png" and r["fixture"] == f
                ),
                None,
            )
            if r is None:
                cells.append("not run")
            elif r["status"] != "ok":
                cells.append("FAIL")
            else:
                c = r["output_check"]
                label = (
                    f"{c['box_pixel_mismatches']} pixel differences"
                    if f == "boxes"
                    else "PNG/nonblank"
                )
                cells.append(f"[{label}](samples/{n}-png-{f}.png)")
        rows.append([NAMES[n]] + cells)
    text.append(table(["Library"] + fixtures, rows))
    for mode in ["parse", "png", "generate"]:
        rows = [r for r in ok if r["mode"] == mode]
        if not rows:
            continue
        text += [
            f"\n## {mode.upper()} measurements\n",
            f"![{mode} latency]({mode}.svg)\n",
            table(
                [
                    "Library",
                    "Fixture",
                    "Median µs",
                    "Min–max µs",
                    "Peak RSS MiB",
                    "Batch iterations",
                ],
                [
                    [
                        NAMES[r["library"]],
                        r["fixture"],
                        f"{r['median_ns'] / 1e3:.3f}",
                        f"{r['min_ns'] / 1e3:.3f}–{r['max_ns'] / 1e3:.3f}",
                        f"{r['peak_rss_bytes'] / 2**20:.2f}",
                        r["samples"][0]["iterations"],
                    ]
                    for r in sorted(rows, key=lambda r: (r["fixture"], r["median_ns"]))
                ],
            ),
        ]
    text += [
        "\n## Memory and code size\n",
        "![Peak process memory](memory.svg)\n",
        "![Source and artifact size](size.svg)\n",
        "RSS is the maximum for each fresh child, including managed runtimes, native libraries, warm-up, and one output write. "
        "It is not allocation volume or retained library heap. Source counts are physical lines/bytes in selected implementation trees; "
        "Rust tests inside src, comments and generated tables are included. External dependencies and font assets are excluded from source counts. "
        "Artifact size includes the adapter and its deployed dependency files; shared system runtimes are excluded. "
        "See the methodology for source roots and language-specific accounting; neither column measures equivalent functionality.\n",
        table(
            ["Library", "Source files", "Physical lines", "Source KiB", "Artifact KiB"],
            [
                [
                    NAMES[n],
                    s["files"],
                    s["lines"],
                    f"{s['bytes'] / 1024:.1f}",
                    f"{s['artifact_bytes'] / 1024:.1f}"
                    if "artifact_bytes" in s
                    else "not built",
                ]
                for n, s in data["sizes"].items()
            ],
        ),
    ]
    if failed:
        text.append("\n## Failures\n")
        text.append(
            table(
                ["Library", "Operation", "Fixture", "Error"],
                [
                    [
                        NAMES[r["library"]],
                        r["mode"],
                        r["fixture"],
                        r["error"].replace("\n", " ").replace("|", "/")[:700],
                    ]
                    for r in failed
                ],
            )
        )
    text += [
        "\n## Environment and provenance\n",
        table(
            ["Property", "Value"],
            [
                [k, str(v).replace("\n", "; ").replace("|", "/")]
                for k, v in data["host"].items()
            ],
        ),
        "\nAll package lock hashes, source revisions, fixture hashes, raw batch timings, and output hashes are saved in [results.json](results.json). "
        "Run the same locked suite on the same idle machine to compare revisions. GitHub-hosted runner measurements should be treated as trends, not stable performance gates.\n",
    ]
    (dest / "README.md").write_text("\n".join(text))


if __name__ == "__main__":
    main()
