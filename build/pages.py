"""Markdown-only gallery generation from independently cached comparison metadata."""

import json
import os
import statistics
import sys
from pathlib import Path

from benchmarks.accuracy.presentation import LEGEND
from benchmarks.formatting import NAMES


def link(page, target, label):
    return f"[{label}]({os.path.relpath(target, Path(page).parent)})"


def compact(page, preview, original, label):
    return link(page, original, "!" + link(page, preview, label))


def result(row):
    score = "unscored" if row.get("score") is None else f"{row['score'] * 100:.2f}% IoU"
    return f"{row['status']} · {score}" + (" · exact" if row.get("exact") else "")


def write(spec, destination):
    rows = [json.loads(Path(p).read_text()) for p in spec["rows"]]
    page = spec["page"]
    base = spec["base"]
    assets = spec.get("assets", base)
    cases = spec["cases"]
    lookup = {c.get("id", c["name"]): c for c in cases}
    libraries = spec["libraries"]
    text = [
        "<!-- Generated by Bazel from cached render/comparison actions. -->",
        "# " + spec["title"],
        LEGEND,
        "All renderer images and measurements are saved observations; their original provenance is retained in results.json." if spec.get("saved") else "Printer and Labelary captures retain their original capture dates. Local renders are cached independently; execution timestamps are recorded per result in results.json.",
        link(page, base + "/README.md", "All comparisons")
        + " · "
        + link(page, "docs/benchmarks/accuracy/README.md", "Accuracy summary"),
    ]
    mode = spec["mode"]
    if mode == "case":
        case = cases[0]
        cid = case.get("id", case["name"])
        text += [
            case.get("purpose", case.get("arguments", "")),
            link(page, spec["source"], "ZPL source"),
            f"Validity: {case.get('validity', 'captured printer case')}. {case.get('notes', '')}",
        ]
        if case.get("source"):
            text.append("Source: " + str(case["source"]))
        if case.get("references"):
            text.append(
                "Zebra programming guide: "
                + " · ".join(
                    link(
                        page,
                        "docs/zpl-zbi2-pg-en.pdf#page=" + str(r["pdf_page"]),
                        r["command"],
                    )
                    for r in case["references"]
                )
            )
        if case.get("capture_eligible") is False:
            text.append(
                "Printer capture excluded: invalid or stateful/device-dependent operations. Local renders remain visible and unscored."
            )
        if spec.get("failure"):
            text.append("Printer capture unavailable: " + spec["failure"])
        reference = spec.get("reference")
        printer = (
            compact(
                page,
                assets + "/previews/" + cid + "-printer.png",
                reference,
                "Printer preview",
            )
            if reference
            else "No scored printer capture"
        )
        for row in rows:
            lib = row["library"]
            prefix = cid + "-" + lib
            text += [
                "## " + lib,
                "**" + NAMES.get(lib, lib) + "**",
                result(row)
                + " · "
                + link(
                    page,
                    base + "/libraries/" + lib + ".md",
                    "All cases for this library",
                ),
            ]
            if lib == "labelary":
                text.append(
                    link(
                        page,
                        "docs/benchmarks/labelary/README.md",
                        "Labelary capture timestamps, HTTP metadata, and original responses",
                    )
                )
            rendered = (
                compact(
                    page,
                    assets + "/previews/" + prefix + ".png",
                    spec["renders"] + "/images/" + prefix + ".png",
                    lib + " render",
                )
                if row["status"] in ["rendered", "blank"]
                else "Render failed; no image"
            )
            difference = (
                compact(
                    page,
                    assets + "/previews/" + prefix + "-diff.png",
                    assets + "/images/" + prefix + "-diff.png",
                    lib + " difference",
                )
                if row.get("iou") is not None
                else "Unavailable"
            )
            text.append(
                "| Printer preview | Library render | Difference |\n|---|---|---|\n| "
                + f"{printer} | {rendered} | {difference}"
                + " |"
            )
            if row.get("output_dimensions"):
                text.append(
                    f"Library dimensions: {row['output_dimensions']}; missing ink: {row['missing']}; extra ink: {row['extra']} pixels."
                )
            if row["status"] not in ["rendered", "blank"]:
                text.append(
                    "~~~text\n"
                    + (
                        row.get("error") or row.get("diagnostic") or row["status"]
                    ).replace("~~~", "~ ~ ~")
                    + "\n~~~"
                )
    else:
        if mode == "index":
            text.append("## Libraries")
            for lib in libraries:
                scores = [
                    r["score"]
                    for r in rows
                    if r["library"] == lib and r.get("score") is not None
                ]
                text.append(
                    link(page, base + "/libraries/" + lib + ".md", NAMES.get(lib, lib))
                    + (
                        f" · {statistics.mean(scores) * 100:.2f}% mean IoU"
                        if scores
                        else " · unscored"
                    )
                )
            text.append(
                link(
                    page,
                    "docs/benchmarks/accuracy/comparisons/features/README.md",
                    "Feature fixtures",
                )
                + " · "
                + link(
                    page,
                    "docs/benchmarks/accuracy/comparisons/external/README.md",
                    "External examples",
                )
            )
        text.append(
            "| Case | Group | Result | Difference |\n|---|---|---|---|"
            if mode == "library"
            else "| Case | Group | Result |\n|---|---|---|"
        )
        seen = set()
        for row in rows:
            cid = row["case"]
            if mode == "index" and cid in seen:
                continue
            seen.add(cid)
            text[-1] += (
                "\n| "
                + link(page, base + "/cases/" + cid + ".md", cid)
                + " | "
                + lookup[cid]["group"]
                + " | "
                + (result(row) if mode == "library" else "See all renderers")
                + " |"
            )
            if mode == "library":
                prefix = cid + "-" + row["library"] + "-diff.png"
                text[-1] += (
                    " "
                    + (
                        compact(
                            page,
                            assets + "/previews/" + prefix,
                            assets + "/images/" + prefix,
                            "Difference",
                        )
                        if "iou" in row
                        else "Unavailable"
                    )
                    + " |"
                )
    output = Path(destination) / page
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n\n".join(text) + "\n")


if __name__ == "__main__":
    write(json.loads(Path(sys.argv[1]).read_text()), sys.argv[2])
